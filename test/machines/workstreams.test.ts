import { expect, test } from "bun:test";
import { join } from "node:path";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { tmpEnv, writeJson } from "../storage/helpers.ts";
import { startFakeAnthropic } from "../fakes/fake-anthropic.ts";
import { MemberSession } from "../../src/workstreams/member.ts";
import { createWorkstreamService } from "../../src/workstreams/index.ts";
import { WorkstreamStore } from "../../src/workstreams/store.ts";
import { RpcClient } from "../../src/sdk/client.ts";
import { SshTransport } from "../../src/machines/ssh.ts";
import { inProcessTransport } from "../../src/sdk/in-process.ts";
import { until } from "../workstreams/helpers.ts";

test("persistent remote Workstream members exchange acknowledged messages and share a live view", async () => {
  const env = tmpEnv(), remoteHome = join(env.root, "remote-state");
  const repo = join(env.root, "remote-repo"), bare = join(env.root, "origin.git"); mkdirSync(repo);
  const git = (args: string[]) => execFileSync("git", args, { cwd: repo, windowsHide: true, stdio: "ignore" });
  git(["init", "-q", "-b", "main"]); git(["config", "user.name", "Fixture"]); git(["config", "user.email", "fixture@example.invalid"]);
  writeFileSync(join(repo, "fixture.txt"), "fixture"); git(["add", "."]); git(["commit", "-qm", "Fixture"]);
  git(["init", "-q", "--bare", bare]); git(["remote", "add", "origin", bare]); git(["push", "-qu", "origin", "main"]);
  const local = await startFakeAnthropic([{ text: "Lead received file event" }, { text: "Lead received remote progress" }, { text: "Lead received recovery event" }, { text: "Lead received recovered progress" }]);
  let sharedFile = "", sharedRequests = 0;
  const remote = await startFakeAnthropic([{ text: "Initial remote task complete" }, () => ({ toolCalls: [{ name: "Read", input: { path: sharedFile } }] }), () => ({ toolCalls: [{ name: "Edit", input: { path: sharedFile, old_text: "Initial shared note", new_text: "Updated by remote member" } }] }), { toolCalls: [{ name: "SendMessage", input: { to: "lead", message: "Remote progress" } }] }, { text: "Remote reply complete" }, { toolCalls: [{ name: "SendMessage", input: { to: "lead", message: "Recovered progress" } }] }, { text: "Recovered reply complete" }]);
  const settings = (url: string, displayName: string) => ({ customModels: [{ provider: "anthropic", model: "fake", displayName, apiKey: "fake-key", baseUrl: url }] });
  writeJson(join(env.rigwellHome, "settings.json"), settings(local.url, "Lead fixture"));
  writeJson(join(remoteHome, "settings.json"), { ...settings(remote.url, "Remote fixture"), worktreeDirectory: join(env.root, "remote-worktrees") });
  const cli = fileURLToPath(new URL("../../src/cli/main.ts", import.meta.url)), script = join(env.root, "fake-ssh-workstream.ts");
  writeFileSync(script, `process.env.RIGWELL_HOME=${JSON.stringify(remoteHome)};process.argv=[process.execPath,${JSON.stringify(cli)},'exec','--input-format','stream-jsonrpc','--output-format','stream-jsonrpc'];await import(${JSON.stringify(cli)});`);
  const children: RpcClient[] = [];
  const connectMachine = async () => {
    const transport = new SshTransport({ name: "fixture", host: "owner@fake" }, "fixture", { executable: [process.execPath, script] }), c = new RpcClient(transport), receive = transport.onMessage;
    transport.onMessage = (line) => { if (JSON.parse(line).method === "rigwell.owned_member_shared_file") sharedRequests++; receive(line); };
    children.push(c); return c;
  };
  let service = createWorkstreamService({ connectMachine });
  let attached: ReturnType<typeof service.attach>;
  const request = async () => ({ selectedOption: "proceed_once" });
  const lead = new MemberSession({ tools: (tools) => attached.wrapTools(tools), request, notify(n) { if (lead.connection.session) service.observe(lead.connection.session, n); } });
  const conn = { session: () => lead.connection.session, request, notify() {} };
  attached = service.attach(conn);
  let view: RpcClient | undefined;
  try {
    await service.ready;
    await lead.call("initialize_session", { cwd: env.root, modelId: "custom:Lead-fixture-0", autonomyLevel: "low" });
    const approved = await service.propose(conn, { title: "Remote coordination", goal: "Fixture", plan: "Remote fixture only" });
    const store = new WorkstreamStore(approved.workstreamId!);
    sharedFile = join(store.path("shared"), "note.txt"); writeFileSync(sharedFile, "Initial shared note");
    const spawned = await service.spawn(lead.connection.session!, { name: "Remote", role: "task", prompt: "Initial fixture", machine: "fixture", cwd: repo, model: "custom:Remote-fixture-0" });
    await until(() => store.agent(spawned.agentId)?.lastSummary === "Initial remote task complete");
    expect(store.agent(spawned.agentId)?.machine).toBe("fixture");
    const member = service.members.get(spawned.agentId)!;
    expect(member.connection.session).toBeUndefined(); expect(member.view?.cwd).toBe(spawned.worktreePath!);
    const listener = service.listeners.create(store, "lead", { on: "file_changed", filter: { agentId: spawned.agentId, glob: "watch.txt" } });
    await service.listeners.whenReady(store, listener.listenerId);
    writeFileSync(join(spawned.worktreePath!, "watch.txt"), "Remote file event");
    const event = await service.listeners.wait(store, "lead", { listenerIds: [listener.listenerId], timeoutMs: 2000 });
    expect(event.events[0]?.trigger).toMatchObject({ path: join(spawned.worktreePath!, "watch.txt") });
    view = new RpcClient(inProcessTransport({ sidePane: false, sharedRemoteSession: service.sharedRemoteSession }));
    const loaded = await view.request("load_session", { sessionId: spawned.sessionId });
    expect(loaded.machine).toBe("fixture"); expect(JSON.stringify(loaded.session.messages)).toContain("Initial remote task complete");
    let changedView: any; try { await view.request("load_session", { sessionId: crypto.randomUUID() }); } catch (e) { changedView = e; }
    expect(changedView?.code).toBe(-32006);
    await view.request("close_session"); await view.close(); view = undefined;
    const message = service.send(lead.connection.session!.id, { to: spawned.agentId, message: "Please report progress", priority: "next" });
    expect(message.delivered).toBe(false);
    await until(() => store.agent(spawned.agentId)?.lastSummary === "Remote reply complete");
    await until(() => !!store.messages().find((m) => m.id === message.messageId)?.readAt);
    expect(store.messages().some((m) => m.from === spawned.agentId && m.to === "lead" && m.text === "Remote progress")).toBe(true);
    expect(remote.requests.length).toBe(5); expect(sharedRequests).toBe(2);
    expect(readFileSync(sharedFile, "utf8")).toBe("Updated by remote member");
    expect(store.agent(spawned.agentId)!.tokens).toBeGreaterThan(0);
    const recoveryListener = service.listeners.create(store, "lead", { on: "file_changed", filter: { agentId: spawned.agentId, glob: "after-restart.txt" }, once: true });
    await service.listeners.whenReady(store, recoveryListener.listenerId);
    await lead.connection.session!.settled();
    attached.close(); await service.stop();
    expect(children.every((c) => c.isClosed)).toBe(true);
    service = createWorkstreamService({ connectMachine }); attached = service.attach(conn);
    await service.ready;
    expect(service.members.get(spawned.agentId)?.view?.cwd).toBe(spawned.worktreePath!);
    expect(JSON.stringify(service.members.get(spawned.agentId)?.view?.uiMessages())).toContain("Remote reply complete");
    expect(remote.requests.length).toBe(5);
    writeFileSync(join(spawned.worktreePath!, "after-restart.txt"), "Recovered remote listener");
    const recovered = await service.listeners.wait(store, "lead", { listenerIds: [recoveryListener.listenerId], timeoutMs: 2000 });
    expect(recovered.events[0]?.trigger).toMatchObject({ path: join(spawned.worktreePath!, "after-restart.txt") });
    service.send(lead.connection.session!.id, { to: spawned.agentId, message: "Report after recovery", priority: "next" });
    await until(() => store.agent(spawned.agentId)?.lastSummary === "Recovered reply complete");
    expect(store.messages().some((m) => m.from === spawned.agentId && m.text === "Recovered progress")).toBe(true);
    expect(remote.requests.length).toBe(7);
    const archived = await service.archive(lead.connection.session!.id, { agentId: spawned.agentId, cleanupWorktree: true });
    expect(archived.worktreeKept).toBe(true); expect(existsSync(spawned.worktreePath!)).toBe(true);
    expect(children.every((c) => c.isClosed)).toBe(true);
  } finally { await view?.close(); attached.close(); await service.stop(); await lead.close(); local.stop(); remote.stop(); env.cleanup(); }
}, 5000);
